"""Q3. np.arange()."""

import numpy as np


numbers_0_to_20 = np.arange(0, 21, 1)
even_numbers_10_to_50 = np.arange(10, 51, 2)
multiples_of_5 = np.arange(5, 101, 5)

print("Numbers from 0 to 20:")
print(numbers_0_to_20)

print("\nEven Numbers from 10 to 50:")
print(even_numbers_10_to_50)

print("\nNumbers from 5 to 100 with Step of 5:")
print(multiples_of_5)
