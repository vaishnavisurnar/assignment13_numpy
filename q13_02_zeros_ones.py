"""Q2. np.zeros() and np.ones()."""

import numpy as np


zeros_1d = np.zeros(8)
ones_2d = np.ones((4, 4))
zeros_matrix = np.zeros((3, 3))

print("1D Array of 8 Zeros:")
print(zeros_1d)

print("\n2D Array of Shape (4, 4) Filled with Ones:")
print(ones_2d)

print("\n3x3 Matrix of Zeros:")
print(zeros_matrix)
